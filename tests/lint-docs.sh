#!/usr/bin/env bash
# lint-docs.sh — revisa la forma de un documento generado por /sdd:docs.
#   tests/lint-docs.sh <archivo.md>...
# Comprueba lo que las reglas del skill pueden garantizar de forma mecánica;
# el contenido (huecos inventados, idioma) sigue necesitando lectura humana.
set -u

[ $# -gt 0 ] || { echo "Uso: $0 <archivo.md>..." >&2; exit 2; }

status=0
for f in "$@"; do
  errs=()
  [ -f "$f" ] || { echo "✗ $f: no existe"; status=1; continue; }
  title="$(sed -n 1p "$f")"

  case "$title" in "# "*) ;; *) errs+=("línea 1 no es un título '# …'") ;; esac
  # Los documentos internos llevan la cabecera en inglés; los de cliente van
  # en el idioma del contenido, así que solo se exige su forma.
  case "$title" in
    "# App flow"*|"# UX brief"*|"# Data structures"*)
      [ "$(sed -n 3p "$f")" = "> Derived view generated by /sdd:docs. Do not edit by hand." ] \
        || errs+=("cabecera: línea 3 distinta de 'Derived view generated by /sdd:docs…'")
      sed -n 4p "$f" | grep -qE '^> Generated: [0-9]{4}-[0-9]{2}-[0-9]{2}$' \
        || errs+=("cabecera: línea 4 debe ser '> Generated: YYYY-MM-DD'")
      sed -n 5p "$f" | grep -qE '^> Sources: .+' \
        || errs+=("cabecera: línea 5 debe ser '> Sources: …'")
      sed -n 6p "$f" | grep -qE '^> If this document disagrees' \
        || errs+=("cabecera: línea 6 debe empezar con '> If this document disagrees'") ;;
    *)
      sed -n 3p "$f" | grep -q '^> .*/sdd:docs' || errs+=("cabecera: línea 3 debe citar /sdd:docs")
      sed -n 4p "$f" | grep -qE '^> [^:]+: [0-9]{4}-[0-9]{2}-[0-9]{2}$' \
        || errs+=("cabecera: línea 4 debe ser '> <Generado>: YYYY-MM-DD'")
      sed -n 5p "$f" | grep -qE '^> [^:]+: .+' || errs+=("cabecera: línea 5 debe listar las fuentes")
      sed -n 6p "$f" | grep -q '^> .' || errs+=("cabecera: falta la línea 6") ;;
  esac

  # Los documentos internos conservan lo escrito a mano bajo este encabezado.
  case "$title" in
    "# App flow"*|"# UX brief"*|"# Data structures"*)
      grep -q '^## Notes (hand-written)$' "$f" || errs+=("falta '## Notes (hand-written)'") ;;
  esac

  # PRD, acceptance y delivery no llevan FR-n; solo la tabla de cambios de alcance.
  case "$title" in
    "# Product requirements"*|"# Acceptance record"*|"# Delivery package"*)
      bad="$(grep -nE 'FR-[0-9]+' "$f" | grep -vE '^[0-9]+:\|' | head -3)"
      [ -z "$bad" ] || errs+=("FR-n fuera de una tabla: $(printf '%s' "$bad" | tr '\n' ' ')") ;;
  esac

  grep -qE '\\\*\\\*|\\_\\_' "$f" && errs+=("escapes rotos del formateador (\\*\\* o \\_\\_)")
  bad="$(grep -n 'TODO: provide' "$f" | grep -vE 'TODO: provide [^ ]' | head -3)"
  [ -z "$bad" ] || errs+=("'TODO: provide' sin descripción: $(printf '%s' "$bad" | tr '\n' ' ')")

  if [ ${#errs[@]} -eq 0 ]; then echo "✓ $f"; else
    status=1; echo "✗ $f"; printf '    - %s\n' "${errs[@]}"
  fi
done
exit $status
